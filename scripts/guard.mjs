// Quality guard: scans src/ for violations of the hard rules in docs/design.md.
// Runs before every build. GUARD_STRICT=1 also fails on owner placeholders (launch gate).
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { extname, join, relative } from "node:path";

const ROOTS = ["src"];
const EXTENSIONS = new Set([".ts", ".tsx", ".css", ".md", ".mdx", ".json"]);
const SKIP_DIRS = new Set(["node_modules", ".next", "migrations"]);
const strict = process.env.GUARD_STRICT === "1";

const rules = [
  { name: "em or en dash", re: /[\u2013\u2014]/g },
  {
    name: "emoji",
    // Check and cross marks (U+2713, U+2717) are typographic; the terminal and chat demos use them.
    re: /[\u{1F300}-\u{1FAFF}\u{1F900}-\u{1F9FF}\u{2600}-\u{2712}\u{2714}-\u{2716}\u{2718}-\u{27BF}\u{1F600}-\u{1F64F}\u{1F680}-\u{1F6FF}]/gu,
  },
  {
    name: "template or generator branding",
    re: /next\.svg|vercel\.svg|Generated by create next app|Create Next App|\bBuilt with\b|\bMade with\b|\bPowered by\b/g,
  },
  { name: "placeholder text", re: /lorem ipsum|\bTODO\b|\bFIXME\b/gi },
  {
    name: "fake social proof",
    re: /\btestimonials?\b|\btrusted by\b|\brated \d|[\u2605\u2B50]|\b\d+(\.\d+)?x (faster|more|better)\b|\b\d{2,}\+ (clients|customers|projects|companies|businesses)\b/gi,
  },
  // Magnetic buttons are allowed (decisions/0014); cursor replacements are not.
  { name: "custom cursor", re: /CustomCursor|cursor-none|mix-blend-difference/gi },
  {
    name: "slop vocabulary",
    re: /\b(seamless(ly)?|cutting[- ]edge|next[- ]gen(eration)?|unlock|elevate|empower(ing)?|supercharge|revolutioni[sz]e|game[- ]chang(ing|er)|leverage|synerg(y|ies)|best[- ]in[- ]class|world[- ]class|state[- ]of[- ]the[- ]art|unleash|transform your|delve|harness|effortless(ly)?|innovative solutions|tailored solutions|holistic|bespoke|passionate about|dedicated team|trusted partner|end[- ]to[- ]end solutions|digital transformation journey|360[- ]degree)\b/gi,
  },
  {
    name: "forbidden motion library import",
    // No library takes over scrolling (decisions/0008); motion is CSS and small components (0011, 0014).
    re: /from ["'](lenis|@studio-freight\/lenis|aos|locomotive-scroll|framer-motion|motion(\/[\w-]+)?|gsap(\/[\w-]+)?|@gsap\/[\w-]+)["']/g,
  },
];
const strictRules = [{ name: "owner placeholder", re: /\[OWNER:/g }];

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) walk(full, out);
    else if (EXTENSIONS.has(extname(entry))) out.push(full);
  }
  return out;
}

const files = ROOTS.flatMap((root) => walk(root));
const active = strict ? [...rules, ...strictRules] : rules;
const violations = [];

for (const file of files) {
  const text = readFileSync(file, "utf8");
  const lines = text.split("\n");
  for (const rule of active) {
    lines.forEach((line, i) => {
      rule.re.lastIndex = 0;
      if (rule.re.test(line))
        violations.push(`${relative(process.cwd(), file)}:${i + 1}  ${rule.name}`);
    });
  }
}

/*
 * Logos are official artwork only (docs/design.md). Tool marks render from the
 * simple-icons package; any other brand mark is an official file in
 * public/logos/ listed with its source URL in src/content/tools.ts. So no SVG
 * file may live under src/ except the site's own icon, and every file in
 * public/logos/ must be named in tools.ts on an entry that has a source.
 */
const OWN_SVGS = new Set(["src/app/icon.svg"]);
function walkAll(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walkAll(full, out);
    else out.push(full);
  }
  return out;
}
for (const file of walkAll("src")) {
  const path = relative(process.cwd(), file).split("\\").join("/");
  if (extname(file) === ".svg" && !OWN_SVGS.has(path)) {
    violations.push(
      `${path}  logo or icon file in src (use simple-icons, or public/logos/ with a source)`,
    );
  }
}
if (existsSync("public/logos")) {
  const toolsFile = "src/content/tools.ts";
  const tools = existsSync(toolsFile) ? readFileSync(toolsFile, "utf8") : "";
  for (const entry of readdirSync("public/logos")) {
    const entryText = tools.split(/\n\s*\{/).find((block) => block.includes(entry)) ?? "";
    if (!/source:\s*["']https:\/\//.test(entryText)) {
      violations.push(`public/logos/${entry}  logo without a source URL in src/content/tools.ts`);
    }
  }
}

if (violations.length) {
  console.error(`Guard found ${violations.length} violation(s):\n` + violations.join("\n"));
  process.exit(1);
}
console.log(`Guard passed (${files.length} files${strict ? ", strict" : ""}).`);
